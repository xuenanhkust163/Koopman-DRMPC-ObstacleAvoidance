"""
Training data generation script.

Generate open-loop simulation data on multiple tracks using a vehicle dynamics model,
collecting state transition tuples (x_t, u_t, x_{t+1}) for Deep Koopman model training.

The data format generated by this script is compatible with data_loader.py:
    - X_t:   Current state, shape (N, 5), order [px, py, v, psi, omega] (legacy order)
    - U_t:   Current control, shape (N, 2), order [a, delta]
    - X_t1:  Next state, shape (N, 5), order [px, py, v, psi, omega]
    - Ts:    Sampling time

where px, py have been z-score normalized.
"""

