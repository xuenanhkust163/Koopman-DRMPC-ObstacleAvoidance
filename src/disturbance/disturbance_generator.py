"""
Generate disturbance signals using Gaussian Mixture Model (GMM).

Section 6.1.3 of the paper: Disturbance w_t is generated from a Gaussian mixture distribution to simulate real uncertainties.

Advantages of Gaussian Mixture Distribution:
1. Capable of modeling multimodal distributions (various disturbance patterns)
2. More flexible than a single Gaussian distribution, can capture complex disturbance characteristics
3. Closer to the uncertainties in real scenarios (e.g., different road conditions, wind speeds, etc.)

Applications of disturbances:
- Added to vehicle dynamics models in simulation environments
- Used to construct Wasserstein fuzzy sets (distributionally robust optimization)
- Evaluate the robustness of MPC controllers under uncertainty
"""

import numpy as np  # Import NumPy library for efficient numerical computation and multi-dimensional array operations
import os  # Import operating system interface module for file and path operations
import sys  # Import system module to modify Python path

# Add the parent directory to the system path to ensure that modules at the same level (e.g., config.py) can be imported
# os.path.dirname(os.path.dirname(os.path.abspath(__file__))) gets the grandparent directory of the current file
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# Import disturbance-related parameters from the configuration file
from config import (
    N_W,  # Disturbance dimension, default is 5 [w_px, w_py, w_v, w_psi, w_omega]
    N_DISTURBANCE_SAMPLES,  # Number of disturbance samples, default 100, used to construct Wasserstein fuzzy sets
    ENABLE_DISTURBANCE,
    NOMINAL_SIGMA,  # Training nominal disturbance standard deviation (single-point truth source)
)


class DisturbanceGenerator:
    """
    Generate disturbance samples from a Gaussian Mixture Distribution.

    Disturbance vector w = [w_px, w_py, w_v, w_psi, w_omega] ∈ R^5
    Physical meanings of each component:
        - w_px: disturbance in the x-direction [meters] (e.g., lateral offset caused by crosswind)
        - w_py: disturbance in the y-direction [meters]
        - w_v: velocity disturbance [meters/second] (e.g., variation in road surface friction)
        - w_psi: yaw angle disturbance [radians] (e.g., uncertainty in the steering system)
        - w_omega: angular velocity disturbance [radians/second] (e.g., disturbance in yaw torque)

    Gaussian mixture model formula:
        p(w) = Σ_{k=1}^{K} π_k * N(w | μ_k, Σ_k)
    Where:
        - K: Number of Gaussian components (n_components)
        - π_k: Weight of the k-th component (weights), Σπ_k = 1
        - μ_k: Mean vector of the k-th component (means)
        - Σ_k: Covariance matrix of the k-th component (simplified using diagonal matrix)

    The disturbances generated by this method have:
    - Multimodal characteristics: can simulate different types of disturbance scenarios
    - Controllable intensity: disturbance size can be adjusted by the sigma parameter
    - Implementability: fixed seed ensures reproducible results
    """

    def __init__(self, sigma=None, n_components=3, seed=42, enabled=None):
        """
        Initialize the disturbance generator and set the parameters of the Gaussian mixture distribution.

        This function creates the parameters of the Gaussian mixture model:
        1. Mean of each Gaussian component (small offsets)
        2. Covariance of each Gaussian component (controlled by scale factors)
        3. Weight of each Gaussian component (uniformly distributed)

        Parameters:
            sigma: float, base noise standard deviation, controls disturbance intensity
                  Default is 0.05, representing a 5% noise level
                  Larger sigma means stronger disturbance
            n_components: int, number of Gaussian mixture components
                         Default is 3, representing the use of 3 different Gaussian distributions
                         More components mean a more complex disturbance distribution
            seed: int, random seed
                 Default is 42, ensures reproducibility
                 The same seed will generate the same disturbance sequence
        """
        self.sigma = sigma if sigma is not None else NOMINAL_SIGMA  # Default to config.NOMINAL_SIGMA
        sigma = self.sigma  # Subsequent formulas use local sigma
        self.n_components = n_components  # Save the number of Gaussian mixture components
        self.enabled = ENABLE_DISTURBANCE if enabled is None else bool(enabled)

        # Create random number generator instance
        # Use RandomState instead of global numpy.random to ensure the independence and controllability of the random number sequence
        self.rng = np.random.RandomState(seed)

        # ================================================================
        # Initialize the parameters of the Gaussian mixture model
        # ================================================================

        # 1. Means of the mixture components (small offsets)
        # Each component has a mean vector of shape (n_components, N_W)
        # Generate random means using the standard normal distribution, then scale to sigma*0.5
        # This ensures the means are small, with disturbances centered around zero but slightly offset
        self.means = self.rng.randn(n_components, N_W) * sigma * 0.5

        # 2. Covariances of the mixture components (diagonal matrices with different scales)
        # Use different scale factors [0.8, 1.0, 1.5] to create components with different variances
        # This simulates different types of disturbances:
        #   - Scale 0.8: smaller disturbances (e.g., slight road unevenness)
        #   - Scale 1.0: moderate disturbances (e.g., normal wind speed variations)
        #   - Scale 1.5: larger disturbances (e.g., strong winds or slippery roads)
        # Only take the first n_components scale factors
        self.scales = np.array([0.8, 1.0, 1.5])[:n_components]

        # 3. Mixture weights (uniformly distributed)
        # All Gaussian components have equal weights, summing up to 1
        # For example, when n_components=3, weights=[1/3, 1/3, 1/3]
        # This means each component has an equal probability of being selected during sampling
        self.weights = np.ones(n_components) / n_components

    def sample(self, n_samples=N_DISTURBANCE_SAMPLES):
        """
        Draw a specified number of disturbance samples from the Gaussian mixture distribution.

        Sampling process (for each sample):
        1. Randomly select a Gaussian component k according to the weight probabilities
        2. Sample from the selected component N(μ_k, σ_k^2*I):
           w = μ_k + ε * sigma * scale_k
           Where ε ~ N(0, I) is standard normal noise

        This method is suitable for:
        - Online simulation: generating new disturbances at each time step
        - Monte Carlo testing: generating a large number of samples to evaluate statistical properties

        Parameters:
            n_samples: int, number of samples to generate
                      Default is set to N_DISTURBANCE_SAMPLES (100) in config.py

        Returns:
            w_samples: numpy array of shape (n_samples, N_W)
                      Each row is a 5-dimensional disturbance vector
                      For example: w_samples[0] = [w_px, w_py, w_v, w_psi, w_omega]
        """
        if not self.enabled:
            return np.zeros((n_samples, N_W))

        # Initialize the sample array, all zeros
        # Shape: (n_samples, N_W) = (100, 5)
        w_samples = np.zeros((n_samples, N_W))

        # Generate samples one by one
        for i in range(n_samples):
            # Step 1: Select a Gaussian component according to the weight probabilities
            # For example: if weights=[0.33, 0.33, 0.34], each component is selected with a probability of about 1/3
            k = self.rng.choice(self.n_components, p=self.weights)

            # Step 2: Sample from the selected Gaussian component
            # Formula: w = μ_k + ε * sigma * scale_k
            # Where:
            #   - μ_k: Mean vector of the k-th component self.means[k]
            #   - ε: Standard normal noise self.rng.randn(N_W)
            #   - sigma: Base noise standard deviation
            #   - scale_k: Scale factor of the k-th component self.scales[k]
            w_samples[i] = (
                self.means[k] +
                self.rng.randn(N_W) * self.sigma * self.scales[k]
            )

        return w_samples  # Return the array of generated disturbance samples

    def sample_single(self):
        """
        Draw a single disturbance sample.

        This method is a simplified version of sample(1), directly returning a one-dimensional array instead of a two-dimensional array.
        Suitable for:
        - Adding disturbances at each time step in online simulations
        - Generating perturbations in real-time control systems

        Returns:
            w: numpy array of shape (N_W,) = (5,)
               A single 5-dimensional disturbance vector [w_px, w_py, w_v, w_psi, w_omega]
        """
        if not self.enabled:
            return np.zeros(N_W)

        # Step 1: Select a Gaussian component according to the weights
        k = self.rng.choice(self.n_components, p=self.weights)

        # Step 2: Generate a sample from the selected component
        # Formula: w = μ_k + ε * sigma * scale_k
        # Return a one-dimensional array of shape (N_W,)
        return (
            self.means[k] +
            self.rng.randn(N_W) * self.sigma * self.scales[k]
        )

    def get_empirical_samples(self, n_samples=N_DISTURBANCE_SAMPLES):
        """
        Obtain a set of fixed empirical samples for constructing Wasserstein fuzzy sets.

        The key differences between this method and sample():
        1. Uses an independent random number generator (seed=0), unaffected by other sampling operations
        2. Ensures the same n_samples always returns the same set of samples
        3. Specifically used for constructing Wasserstein fuzzy sets in distributionally robust optimization

        Applications in K-DRMPC:
        - These empirical samples serve as historical disturbance data
        - Used to construct the central distribution of the Wasserstein ball (fuzzy set)
        - Considered in the MPC optimization within all possible distributions of this fuzzy set
        - Enhances the robustness of the controller against disturbance uncertainties

        Parameters:
            n_samples: int, number of samples to generate
                      Default is set to N_DISTURBANCE_SAMPLES (100) in config.py

        Returns:
            w_empirical: numpy array of shape (n_samples, N_W)
                        A fixed set of empirical samples for distributionally robust optimization
                        For example: (100, 5) represents 100 samples of 5-dimensional disturbances
        """
        if not self.enabled:
            return np.zeros((n_samples, N_W))

        # Use an independent random number generator to ensure implementability
        # Fixed seed of 0, ensuring completely reproducible results
        # This generator is not affected by self.rng, guaranteeing the stability of the empirical samples
        rng_fixed = np.random.RandomState(0)

        # Initialize the sample array
        samples = np.zeros((n_samples, N_W))

        # Generate samples one by one (same logic as in the sample method)
        for i in range(n_samples):
            # Select Gaussian component
            k = rng_fixed.choice(self.n_components, p=self.weights)
            # Generate sample: w = μ_k + ε * sigma * scale_k
            samples[i] = (
                self.means[k] +
                rng_fixed.randn(N_W) * self.sigma * self.scales[k]
            )

        return samples  # Return the fixed set of empirical samples
